import catalogue from "./catalogue.json";

const byId = new Map(catalogue.map((item) => [item.id, item]));

// Every plan step points at a catalogue entry by id. Unknown ids are dropped,
// which is the same check the plan generator will apply to model output.
export function catalogueItem(id) {
  return byId.get(id) ?? null;
}

